#!/usr/bin/env node
// Licence ledger check for kit and car assets (Kit v1, phase A).
//
// Every kit asset has assets_source/masters/kit/<id>/source.json and every car has assets_source/masters/cars/<id>/source.json:
//   { name, url, author, licence, licence_url, downloaded (YYYY-MM-DD), files: [master files in that folder], notes }
//   kit ledgers also: sha256 { file: hex } and master_release (the GitHub release tag holding the masters: they are NOT
//   in git; `node tools/assets/masters.mjs fetch` downloads them).
//   cars also list `shipped`: the files under web/public/assets/cars/ made from them (no car master lives in the repo).
//   optional: `changes` (what we changed, for the CC BY credit), `owner_approval` (date: required for CC-BY-SA).
//
// It fails (exit 1) when:
//   - a ledger is missing a field, has an unparseable date, or a licence outside the allowed list
//     (CC0-1.0, CC-BY-3.0, CC-BY-4.0, CC-BY-NC-4.0; CC-BY-SA-3.0 / CC-BY-SA-4.0 only with `owner_approval`);
//   - a kit ledger has no sha256 for one of its files or no master_release; a kit master is tracked by git;
//   - a kit master present here differs from its sha256 (masters are read-only) or is over the size budget
//     (data/asset_budgets.json `maxFileMB` if that file exists, else 50 MB); masters not fetched are not checked;
//   - a file in a kit folder is not listed in its ledger (masters are added on purpose, with their licence);
//   - a generated kit file (web/public/assets/kit/, ue5/SourceArt/Kit/) is not under a folder named after a kit id
//     (generated manifest.json indexes are allowed; every id they name must have a ledger);
//   - a car model or texture under web/public/assets/cars/ is in no car ledger, or a `shipped` file does not exist;
//   - the "Kit assets" section of CREDITS.md is not what the ledgers generate.
//
//   node tools/assets/check_licences.mjs            check (CI)
//   node tools/assets/check_licences.mjs --write    also rewrite the CREDITS.md "Kit assets" section
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const KIT = path.join(ROOT, 'assets_source', 'masters', 'kit');
const CARS = path.join(ROOT, 'assets_source', 'masters', 'cars');
const GENERATED = ['web/public/assets/kit', 'ue5/SourceArt/Kit'];
const CAR_ASSETS = 'web/public/assets/cars';
const MODEL_EXT = /\.(glb|gltf|bin|ktx2|png|jpe?g|webp|exr|hdr|fbx|obj|usdz?)$/i;
const ALLOWED = new Set(['CC0-1.0', 'CC-BY-3.0', 'CC-BY-4.0', 'CC-BY-NC-4.0']);
const NEEDS_APPROVAL = new Set(['CC-BY-SA-3.0', 'CC-BY-SA-4.0']);
const FIELDS = ['name', 'url', 'author', 'licence', 'licence_url', 'downloaded', 'files', 'notes'];
const BEGIN = '<!-- kit-assets:begin (generated by tools/assets/check_licences.mjs from the kit ledgers: do not edit by hand) -->';
const END = '<!-- kit-assets:end -->';

const write = process.argv.includes('--write');
const problems = [];
const bad = (where, msg) => problems.push(`${where}: ${msg}`);
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

let maxMB = 50;
const budgetPath = path.join(ROOT, 'data', 'asset_budgets.json');
if (fs.existsSync(budgetPath)) {
  const b = JSON.parse(fs.readFileSync(budgetPath, 'utf8'));
  if (typeof b.maxFileMB === 'number') maxMB = b.maxFileMB;
}

/** size in bytes; a Git LFS pointer (CI checkouts without LFS) reports the real object's size */
function fileSize(p) {
  const st = fs.statSync(p);
  if (st.size < 1024) {
    const t = fs.readFileSync(p, 'utf8');
    if (t.startsWith('version https://git-lfs.github.com/spec/v1')) {
      const m = /size (\d+)/.exec(t);
      if (m) return Number(m[1]);
    }
  }
  return st.size;
}

function sha256(p) {
  return createHash('sha256').update(fs.readFileSync(p)).digest('hex');
}

/** files git tracks under a folder ([] when git is not available) */
function tracked(dir) {
  try {
    return execFileSync('git', ['ls-files', '--', rel(dir)], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);
  } catch {
    return [];
  }
}

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function readLedgers(dir, kind) {
  const ledgers = [];
  if (!fs.existsSync(dir)) return ledgers;
  for (const id of fs.readdirSync(dir).sort()) {
    const folder = path.join(dir, id);
    if (!fs.statSync(folder).isDirectory()) continue;
    const p = path.join(folder, 'source.json');
    if (!fs.existsSync(p)) { bad(rel(folder), 'no source.json (every kit / car asset needs a licence ledger)'); continue; }
    let d;
    try { d = JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { bad(rel(p), `not valid JSON (${e.message})`); continue; }
    const where = rel(p);
    for (const f of FIELDS) if (d[f] === undefined || d[f] === null || (typeof d[f] === 'string' && !d[f].trim() && f !== 'notes')) bad(where, `missing "${f}"`);
    if (!Array.isArray(d.files)) bad(where, '"files" must be a list');
    if (typeof d.downloaded === 'string' && !/^\d{4}-\d{2}-\d{2}$/.test(d.downloaded)) bad(where, `"downloaded" must be YYYY-MM-DD (got ${d.downloaded})`);
    if (typeof d.licence_url === 'string' && !/^https?:\/\//.test(d.licence_url)) bad(where, '"licence_url" must be a link to the licence');
    if (ALLOWED.has(d.licence)) { /* fine */ }
    else if (NEEDS_APPROVAL.has(d.licence)) { if (!d.owner_approval) bad(where, `${d.licence} needs the owner's approval recorded in "owner_approval" (our edits would have to stay ${d.licence})`); }
    else bad(where, `licence "${d.licence}" is not allowed in the repo (allowed: ${[...ALLOWED].join(', ')}; CC-BY-SA with approval). Fab / Megascans / Textures.com / editorial / paid / unclear: ue5/Content/ThirdParty/ only`);
    ledgers.push({ id, kind, folder, path: p, d });
  }
  return ledgers;
}

const kit = readLedgers(KIT, 'kit');
const cars = readLedgers(CARS, 'car');

// ---- no Git LFS in the public repo (strangers cloning would consume the owner's monthly LFS bandwidth quota)
const gitattributesPath = path.join(ROOT, '.gitattributes');
if (fs.existsSync(gitattributesPath) && /\bfilter=lfs\b/.test(fs.readFileSync(gitattributesPath, 'utf8'))) {
  bad('.gitattributes', 'uses filter=lfs: never use Git LFS in the public repo (put large masters on GitHub Releases instead)');
}

// ---- kit masters
for (const L of kit) {
  const listed = new Set((L.d.files ?? []).map((f) => path.normalize(f)));
  if (!L.d.master_release) bad(rel(L.path), 'missing "master_release" (the GitHub release tag that holds the masters)');
  for (const f of listed) {
    const p = path.join(L.folder, f);
    const want = L.d.sha256?.[f];
    if (!/^[0-9a-f]{64}$/.test(want ?? '')) bad(rel(L.path), `missing "sha256" for ${f}`);
    if (!fs.existsSync(p)) continue;   // not fetched here (CI, a fresh clone): the ledger is what is checked
    const mb = fileSize(p) / 1048576;
    if (mb > maxMB) bad(rel(p), `${mb.toFixed(1)} MB is over the ${maxMB} MB per-file budget`);
    if (want && sha256(p) !== want) bad(rel(p), 'differs from its ledger sha256 (masters are read-only once added)');
  }
  for (const t of tracked(L.folder)) {
    const r = path.normalize(path.relative(rel(L.folder), t));
    if (r !== 'source.json' && !r.startsWith(`evidence${path.sep}`)) bad(t, 'a master is tracked by git: masters live on the GitHub release (.gitignore)');
  }
  for (const p of walk(L.folder)) {
    const r = path.normalize(path.relative(L.folder, p));
    if (r === 'source.json' || r.startsWith(`evidence${path.sep}`)) continue;   // the ledger and its licence evidence
    if (!listed.has(r)) bad(rel(p), `not listed in ${rel(L.path)} "files"`);
  }
}

// ---- generated kit files belong to a kit id
const kitIds = new Set(kit.map((L) => L.id));
for (const g of GENERATED) {
  for (const p of walk(path.join(ROOT, g))) {
    const parts = rel(p).split('/');
    if (path.basename(p) === 'manifest.json') {   // a generated index: every asset it names must have a ledger
      let m;
      try { m = JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { bad(rel(p), `not valid JSON (${e.message})`); continue; }
      const ids = [];
      JSON.stringify(m, (k, v) => { if (k === 'id' && typeof v === 'string') ids.push(v); return v; });
      for (const id of ids) if (!kitIds.has(id)) bad(rel(p), `names "${id}", which has no kit ledger`);
      continue;
    }
    if (!parts.some((s) => kitIds.has(s))) bad(rel(p), 'generated kit file outside a folder named after a kit id (no licence ledger)');
  }
}

// ---- cars: every shipped model / texture is in exactly one ledger
const owner = new Map();
for (const L of cars) {
  for (const f of L.d.shipped ?? []) {
    if (!fs.existsSync(path.join(ROOT, f))) bad(rel(L.path), `shipped file ${f} does not exist`);
    if (owner.has(f)) bad(f, `in two car ledgers (${owner.get(f)}, ${L.id})`);
    owner.set(f, L.id);
  }
  if (!Array.isArray(L.d.shipped) || !L.d.shipped.length) bad(rel(L.path), 'a car ledger lists the files it ships ("shipped")');
}
for (const p of walk(path.join(ROOT, CAR_ASSETS))) {
  const r = rel(p);
  if (MODEL_EXT.test(r) && !owner.has(r)) bad(r, 'car asset without a licence ledger (assets_source/masters/cars/<id>/source.json "shipped")');
}

// ---- CREDITS.md "Kit assets" section
function creditsSection() {
  const lines = ['## Kit assets', BEGIN, ''];
  if (!kit.length) lines.push('_No kit assets yet._', '');
  const by = (lic) => kit.filter((L) => L.d.licence === lic || (lic === 'CC-BY' && /^CC-BY-(3|4)\.0$/.test(L.d.licence)));
  const ccby = kit.filter((L) => /^CC-BY-(SA-)?(3|4)\.0$/.test(L.d.licence));
  if (ccby.length) {
    lines.push('Licensed CC BY (credit required):', '');
    for (const L of ccby) {
      const d = L.d, ver = d.licence.replace(/^CC-BY-(SA-)?/, '');
      lines.push(`- **${d.name}** by ${d.author} (${d.url}), licensed ${d.licence.replace(/-/g, ' ').replace('CC BY SA', 'CC BY-SA')} (${d.licence_url}). `
        + `Changes: ${d.changes || 'converted, resized and compressed for the web and Unreal exports (tools/assets/).'} Kit id \`${L.id}\`.`);
      void ver;
    }
    lines.push('');
  }
  const nc = kit.filter((L) => L.d.licence === 'CC-BY-NC-4.0');
  if (nc.length) {
    lines.push('Licensed CC BY-NC 4.0 (own photos and own work):', '');
    for (const L of nc) lines.push(`- **${L.d.name}** by ${L.d.author}, CC BY-NC 4.0 (${L.d.licence_url}). Kit id \`${L.id}\`.`);
    lines.push('');
  }
  const cc0 = by('CC0-1.0');
  if (cc0.length) {
    lines.push('CC0 1.0 (no credit required; listed with thanks):', '');
    for (const L of cc0) lines.push(`- **${L.d.name}** by ${L.d.author} (${L.d.url}). Kit id \`${L.id}\`.`);
    lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}
const creditsPath = path.join(ROOT, 'CREDITS.md');
const credits = fs.readFileSync(creditsPath, 'utf8');
const section = creditsSection();
let next;
const b = credits.indexOf('## Kit assets'), e = credits.indexOf(END);
if (b >= 0 && e > b) next = credits.slice(0, b) + section + credits.slice(e + END.length);
else next = credits.replace(/\s*$/, '\n\n') + section + '\n';
if (next !== credits) {
  if (write) { fs.writeFileSync(creditsPath, next); console.log('CREDITS.md: "Kit assets" section rewritten'); }
  else bad('CREDITS.md', 'the "Kit assets" section is out of date: run node tools/assets/check_licences.mjs --write');
}

console.log(`ledgers: ${kit.length} kit, ${cars.length} cars; per-file budget ${maxMB} MB`);
if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}
console.log('licence ledgers OK');
