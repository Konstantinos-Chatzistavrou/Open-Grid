#!/usr/bin/env node
// Builds a STANDALONE copy of the conformance suite (runner, spec, tyre files, case list, MFeval's reference output, licences, optional example logs) that can be handed to someone who does not have this repository.
//   node conformance/pack.mjs [--out dist/opengrid-conformance] [--adapter core/build/rs_conformance --car data/cars/vela_gt.json]
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, '..');
const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 && i + 1 < argv.length ? argv[i + 1] : d; };
const out = path.resolve(opt('--out', path.join(root, 'dist/opengrid-conformance')));
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'tyre/files'), { recursive: true });
fs.mkdirSync(path.join(out, 'LICENSES'), { recursive: true });
for (const f of ['README.md', 'SPEC.md', 'run.mjs']) fs.copyFileSync(path.join(here, f), path.join(out, f));

const mf = JSON.parse(fs.readFileSync(path.join(here, 'tyre/manifest.json'), 'utf8'));
const dir = path.join(here, 'tyre');
const copy = (rel, name) => { fs.copyFileSync(path.resolve(dir, rel), path.join(out, 'tyre/files', name)); return `files/${name}`; };
mf.cases = copy(mf.cases, 'cases.csv');
for (const t of mf.tyres) { t.tir = copy(t.tir, `${t.tag}.tir`); t.golden = copy(t.golden, `${t.tag}_reference.csv`); }
fs.writeFileSync(path.join(out, 'tyre/manifest.json'), JSON.stringify(mf, null, 2) + '\n');

fs.copyFileSync(path.join(root, 'tools/validation/mfeval/LICENSE.txt'), path.join(out, 'LICENSES/MFeval-BSD-3.txt'));
fs.copyFileSync(path.join(root, 'data/tires/LICENSE-projectchrono.txt'), path.join(out, 'LICENSES/ProjectChrono-BSD-3.txt'));
fs.writeFileSync(path.join(out, 'LICENSES.md'), `# Licences in this pack

- **run.mjs, SPEC.md, README.md**: Apache-2.0 (OpenGrid).
- **tyre/files/example_*.tir and the reference output of those tyres**: MFeval's own example tyres and MFeval's output, BSD-3-Clause, Copyright (c) 2020 Marco Furlan Tassara (LICENSES/MFeval-BSD-3.txt). The author does not state where the example tyres' data came from.
- **tyre/files/audi_pac2002.tir and its reference output**: Project Chrono's Audi 245/40 R18 PAC2002 tyre, BSD-3-Clause, Copyright (c) 2016 Project Chrono Development Team (LICENSES/ProjectChrono-BSD-3.txt).
- **tyre/files/cases.csv, tyre/files/opengrid_mf6*_synthetic.tir and their reference output**: OpenGrid, **CC BY-NC 4.0 (non-commercial)**. The synthetic tyres also contain the Chrono coefficients above (BSD-3 notice kept in the files).
  If you need these under terms that allow commercial use, ask the OpenGrid maintainers; the rest of the pack is usable commercially under the notices above.
`);

if (opt('--adapter') && fs.existsSync(opt('--adapter'))) {
  const car = path.resolve(opt('--car', path.join(root, 'data/cars/vela_gt.json')));
  const ex = path.join(out, 'examples/' + path.basename(car, '.json'));
  fs.mkdirSync(ex, { recursive: true });
  const r = spawnSync(path.resolve(opt('--adapter')), ['vehicle', car, ex], { encoding: 'utf8' });
  if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
  fs.writeFileSync(path.join(out, 'examples/README.md'), `Example output of the reference adapter for ${path.basename(car)} (spec.json and the eight logs): the format \`run.mjs vehicle\` reads. Generated by \`rs_conformance vehicle\`; judge it with \`node run.mjs vehicle --spec examples/${path.basename(car, '.json')}/spec.json --logs examples/${path.basename(car, '.json')}\`.\n`);
}
console.log(`wrote ${out}`);
