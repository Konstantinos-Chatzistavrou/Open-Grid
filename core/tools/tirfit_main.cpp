// Apache-2.0 - rs_tirfit: fit a Magic Formula tyre property file (.tir) to measured tyre curves (see rs/tirfit.hpp and docs/own_tyre_data.md).
//
//   rs_tirfit <data.csv> --template <tyre.tir> --out <fitted.tir> [--report report.json] [--set KEY=VALUE]... [--angle-sign -1] [--no-aligning] [--no-combined] [--name text]
//
// data.csv: one row per measured point, header names as in rs/tirfit.hpp (fz, kappa, alpha | alpha_deg, gamma | gamma_deg, vx, pressure | pressure_kpa, fx, fy, mz, mx), forces in N, moments in N m,
// signs as in the tyre-file convention (--angle-sign -1 for SAE-signed angles). The template supplies the geometry, the nominal load and every coefficient the data cannot determine:
// give it the right size with --set UNLOADED_RADIUS=0.31 --set WIDTH=0.225 --set ASPECT_RATIO=0.45 --set RIM_RADIUS=0.2286 --set NOMPRES=220000 --set INFLPRES=220000 --set FNOMIN=4000.
#include <algorithm>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <iostream>
#include <sstream>
#include "rs/tirfit.hpp"

namespace {
bool slurp(const std::string& path, std::string& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return false;
    std::stringstream ss;
    ss << f.rdbuf();
    out = ss.str();
    return true;
}
std::string base_name(const std::string& p) {
    const std::size_t k = p.find_last_of("/\\");
    return k == std::string::npos ? p : p.substr(k + 1);
}
}  // namespace

int main(int argc, char** argv) {
    using namespace rs;
    if (argc < 2) {
        std::fprintf(stderr, "usage: rs_tirfit <data.csv> --template <tyre.tir> --out <fitted.tir> [--report report.json] [--set KEY=VALUE]... [--angle-sign -1] [--no-aligning] [--no-combined] [--name text]\n       rs_tirfit --make-demo <truth.tir> <out.csv> [noise]\n");
        return 2;
    }
    if (std::string(argv[1]) == "--make-demo") {
        // rs_tirfit --make-demo <truth.tir> <out.csv> [noise]: SYNTHETIC rows from a known tyre, for trying the pipeline without data of your own
        if (argc < 4) { std::fprintf(stderr, "usage: rs_tirfit --make-demo <truth.tir> <out.csv> [noise, e.g. 0.01]\n"); return 2; }
        std::string text, err;
        mf62::Params truth;
        if (!slurp(argv[2], text) || !mf62::parse_tir(text, truth, err)) { std::fprintf(stderr, "cannot read tyre %s: %s\n", argv[2], err.c_str()); return 1; }
        tirfit::SweepSpec spec;
        spec.noise = argc > 4 ? std::atof(argv[4]) : 0.01;
        const std::vector<tirfit::Sample> rows = tirfit::synthetic_sweep(truth, spec);
        std::ofstream(argv[3], std::ios::binary) << "# SYNTHETIC data generated by rs_tirfit --make-demo from " << base_name(argv[2]) << " with noise " << spec.noise << ": not a measurement.\n" << tirfit::to_csv(rows);
        std::printf("wrote %zu synthetic rows to %s\n", rows.size(), argv[3]);
        return 0;
    }
    std::string csv_path = argv[1], template_path, out_path, report_path, name;
    double angle_sign = 1.0;
    tirfit::Options opt;
    std::vector<std::pair<std::string, double>> sets;
    for (int i = 2; i < argc; ++i) {
        const std::string a = argv[i];
        auto next = [&]() -> std::string { return i + 1 < argc ? std::string(argv[++i]) : std::string(); };
        if (a == "--template") template_path = next();
        else if (a == "--out") out_path = next();
        else if (a == "--report") report_path = next();
        else if (a == "--name") name = next();
        else if (a == "--angle-sign") angle_sign = std::atof(next().c_str()) < 0 ? -1.0 : 1.0;
        else if (a == "--no-aligning") opt.fit_aligning = false;
        else if (a == "--no-combined") opt.fit_combined = false;
        else if (a == "--set") {
            const std::string kv = next();
            const std::size_t eq = kv.find('=');
            if (eq == std::string::npos) { std::fprintf(stderr, "--set needs KEY=VALUE, got '%s'\n", kv.c_str()); return 2; }
            sets.emplace_back(kv.substr(0, eq), std::atof(kv.substr(eq + 1).c_str()));
        } else { std::fprintf(stderr, "unknown argument '%s'\n", a.c_str()); return 2; }
    }
    if (template_path.empty() || out_path.empty()) { std::fprintf(stderr, "--template and --out are required\n"); return 2; }

    std::string csv, tmpl_text, err;
    if (!slurp(csv_path, csv)) { std::fprintf(stderr, "cannot read %s\n", csv_path.c_str()); return 1; }
    if (!slurp(template_path, tmpl_text)) { std::fprintf(stderr, "cannot read %s\n", template_path.c_str()); return 1; }
    std::vector<tirfit::Sample> data;
    if (!tirfit::read_csv(csv, data, err, angle_sign)) { std::fprintf(stderr, "%s: %s\n", csv_path.c_str(), err.c_str()); return 1; }
    mf62::Params tyre;
    if (!mf62::parse_tir(tmpl_text, tyre, err)) { std::fprintf(stderr, "%s: %s\n", template_path.c_str(), err.c_str()); return 1; }
    const mf62::Params before = tyre;

    bool fnomin_given = false;
    for (const auto& [k, v] : sets) {
        std::string key = k;
        for (char& c : key) c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
        if (key == "FNOMIN") fnomin_given = true;
        if (!tirfit::set_coefficient(tyre, key, v)) { std::fprintf(stderr, "--set: '%s' is not a coefficient rs::mf62 reads\n", k.c_str()); return 2; }
    }
    if (!fnomin_given) {
        std::vector<double> fz;
        for (const auto& s : data) fz.push_back(s.fz);
        std::nth_element(fz.begin(), fz.begin() + static_cast<std::ptrdiff_t>(fz.size() / 2), fz.end());
        tyre.fnomin = std::floor(fz[fz.size() / 2] + 0.5);
        std::printf("FNOMIN not given: using the median measured load, %.0f N\n", tyre.fnomin);
    }

    const tirfit::Result res = tirfit::fit(tyre, data, opt);
    std::printf("%s", tirfit::report_text(res).c_str());

    std::vector<std::string> header = {
        "Fitted by rs_tirfit (OpenGrid) from " + base_name(csv_path) + (name.empty() ? "" : " (" + name + ")") + ", starting from the template " + base_name(template_path) + ".",
        "A least-squares fit to the supplied data, NOT a manufacturer's file: valid only inside the data's range of load, slip and camber (the limits below were set from it).",
        "Coefficients the data did not determine keep the template's values; the licence of the template's numbers still applies to those.",
        "Every comment line BELOW this header (descriptions, copyright and licence notices) belongs to the template tyre and describes IT, not the fitted tyre; the notices are kept on purpose.",
    };
    for (const auto& s : res.stages) {
        char buf[200];
        if (s.ran) std::snprintf(buf, sizeof buf, "stage %s (%s): %d rows, rms %.4g (%.2f %% of peak)", s.name.c_str(), s.channel.c_str(), s.rows, s.rms, s.rms_percent_of_peak);
        else std::snprintf(buf, sizeof buf, "stage %s (%s): not fitted (%s)", s.name.c_str(), s.channel.c_str(), s.note.c_str());
        header.push_back(buf);
    }
    const std::string out = tirfit::write_tir(tmpl_text, before, res.params, res.fitted_keys, header);
    std::ofstream(out_path, std::ios::binary) << out;
    if (!report_path.empty()) std::ofstream(report_path) << tirfit::report_json(res) << "\n";
    std::printf("wrote %s\n", out_path.c_str());
    return 0;
}
