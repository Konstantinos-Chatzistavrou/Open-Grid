/** Fit. `sets`: "KEY=VALUE;KEY=VALUE" applied to the template before the fit. Returns JSON: {"ok":true,"report":{...},"tir":"..."} or {"ok":false,"error":"..."}. */
const char* lab_fit(const char* csv, const char* template_tir, const char* sets, double angle_sign, int fit_aligning, int fit_combined) {
    using namespace rs;
    std::string err;
    std::vector<tirfit::Sample> data;
    if (!tirfit::read_csv(csv, data, err, angle_sign < 0 ? -1.0 : 1.0)) { g_fit = "{\"ok\":false,\"error\":\"data: " + esc(err) + "\"}"; return g_fit.c_str(); }
    mf62::Params tyre;
    if (!mf62::parse_tir(template_tir, tyre, err)) { g_fit = "{\"ok\":false,\"error\":\"template: " + esc(err) + "\"}"; return g_fit.c_str(); }
    const mf62::Params before = tyre;
    bool fnomin_given = false;
    std::string s(sets ? sets : ""), item;
    for (std::size_t i = 0; i <= s.size(); ++i) {
        if (i == s.size() || s[i] == ';') {
            const std::size_t eq = item.find('=');
            if (eq != std::string::npos) {
                std::string key = item.substr(0, eq);
                if (key == "FNOMIN") fnomin_given = true;
                if (!tirfit::set_coefficient(tyre, key, std::atof(item.substr(eq + 1).c_str()))) { g_fit = "{\"ok\":false,\"error\":\"not a coefficient: " + esc(key) + "\"}"; return g_fit.c_str(); }
            }
            item.clear();
        } else item += s[i];
    }
    if (!fnomin_given) {
        std::vector<double> fz;
        for (const auto& d : data) fz.push_back(d.fz);
        std::nth_element(fz.begin(), fz.begin() + static_cast<std::ptrdiff_t>(fz.size() / 2), fz.end());
        tyre.fnomin = std::floor(fz[fz.size() / 2] + 0.5);
    }
    tirfit::Options opt;
    opt.fit_aligning = fit_aligning != 0;
    opt.fit_combined = fit_combined != 0;
    const tirfit::Result res = tirfit::fit(tyre, data, opt);
    std::vector<std::string> header = {"Fitted in the browser by the OpenGrid Tyre Lab (rs_tirfit, WebAssembly) from your data.",
                                       "A least-squares fit, NOT a manufacturer's file: valid only inside the data's range of load, slip and camber.",
                                       "Coefficients the data did not determine keep the template's values; the template's licence still applies to those numbers (the page adds its notice above)."};
    const std::string tir = tirfit::write_tir(template_tir, before, res.params, res.fitted_keys, header);
    g_fit = "{\"ok\":true,\"report\":" + tirfit::report_json(res) + ",\"fnomin\":" + std::to_string(res.params.fnomin) + ",\"tir\":\"" + esc(tir) + "\"}";
    return g_fit.c_str();
}

/** SYNTHETIC rows from a known tyre, as CSV (1 % noise unless `noise` says otherwise). */
const char* lab_demo(const char* truth_tir, double noise) {
    using namespace rs;
    std::string err;
    mf62::Params truth;
    if (!mf62::parse_tir(truth_tir, truth, err)) { g_demo = ""; return g_demo.c_str(); }
    tirfit::SweepSpec spec;
    spec.noise = noise;
    g_demo = "# SYNTHETIC data generated by the Tyre Lab from a known tyre: not a measurement.\n" + tirfit::to_csv(tirfit::synthetic_sweep(truth, spec));
    return g_demo.c_str();
}

/** The rows exactly as rs::tirfit parses them, as JSON [[fz,kappa,alpha,gamma,fx,fy,mz],...] (null = not measured), or {"error":"..."}: the page plots what the fit sees. */
const char* lab_rows(const char* csv, double angle_sign) {
    std::vector<rs::tirfit::Sample> d;
    std::string err;
    if (!rs::tirfit::read_csv(csv, d, err, angle_sign < 0 ? -1.0 : 1.0)) { g_rows = "{\"error\":\"" + esc(err) + "\"}"; return g_rows.c_str(); }
    g_rows = "[";
    char buf[200];
    auto num = [&](double v) { if (std::isnan(v)) return std::string("null"); std::snprintf(buf, sizeof buf, "%.6g", v); return std::string(buf); };
    for (std::size_t i = 0; i < d.size(); ++i) {
        const auto& r = d[i];
        g_rows += (i ? ",[" : "[") + num(r.fz) + "," + num(r.kappa) + "," + num(r.alpha) + "," + num(r.gamma) + "," + num(r.fx) + "," + num(r.fy) + "," + num(r.mz) + "]";
    }
    g_rows += "]";
    return g_rows.c_str();
}

/** The geometry a tyre file declares, as JSON, to prefill the form. */
const char* lab_tyre_info(const char* tir) {
    rs::mf62::Params p;
    std::string err;
    if (!rs::mf62::parse_tir(tir, p, err)) { g_info = "{\"ok\":false,\"error\":\"" + esc(err) + "\"}"; return g_info.c_str(); }
    char buf[500];
    std::snprintf(buf, sizeof buf, "{\"ok\":true,\"FNOMIN\":%.6g,\"UNLOADED_RADIUS\":%.6g,\"WIDTH\":%.6g,\"ASPECT_RATIO\":%.6g,\"RIM_RADIUS\":%.6g,\"NOMPRES\":%.6g,\"INFLPRES\":%.6g,\"FITTYP\":%d}", p.fnomin, p.unloaded_radius, p.width, p.aspect_ratio,
                  p.rim_radius, p.nompres, p.inflpres, p.fittyp);
    g_info = buf;
    return g_info.c_str();
}

/** n points of a sweep: channel 0 = Fx over kappa, 1 = Fy over alpha, 2 = Mz over alpha (x from x0 to x1, rad for alpha), at load fz and camber gamma, limits off so the whole range is drawn. Returns n; read with lab_curve_ptr(). */
int lab_curve(const char* tir, int channel, double fz, double gamma, double x0, double x1, int n) {
    using namespace rs;
    g_curve.assign(static_cast<std::size_t>(n > 0 ? n : 0), 0.0);
    mf62::Params p;
    std::string err;
    if (!mf62::parse_tir(tir, p, err) || n < 2) return 0;
    const mf62::Modes modes = mf62::modes_from_use_mode(211);
    for (int i = 0; i < n; ++i) {
        const double x = x0 + (x1 - x0) * i / (n - 1);
        mf62::Input in;
        in.fz = fz; in.gamma = gamma; in.vx = p.longvl;
        if (channel == 0) in.kappa = x; else in.alpha = x;
        const mf62::Output o = mf62::evaluate(p, in, modes);
        const double v = channel == 0 ? o.fx : (channel == 1 ? o.fy : o.mz);
        g_curve[static_cast<std::size_t>(i)] = std::isfinite(v) ? v : 0.0;
    }
    return n;
}
const double* lab_curve_ptr() { return g_curve.data(); }

