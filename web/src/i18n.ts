const LANG_KEY = 'nr.lang.v1';
let currentLang: LangCode = 'en';

export function initLang(): LangCode {
  try {
    const saved = localStorage.getItem(LANG_KEY) as LangCode | null;
    if (saved && saved in STRINGS) currentLang = saved;
    else {
      const nav = (navigator.language || 'en').slice(0, 2).toLowerCase() as LangCode;
      if (nav in STRINGS) currentLang = nav;
    }
  } catch { /* storage blocked */ }
  document.documentElement.lang = currentLang;
  return currentLang;
}

export function getLang(): LangCode { return currentLang; }

export function setLang(code: LangCode) {
  if (!(code in STRINGS)) return;
  currentLang = code;
  document.documentElement.lang = code;
  try { localStorage.setItem(LANG_KEY, code); } catch { /* blocked */ }
}

export function t(key: string, fallback?: string): string {
  return STRINGS[currentLang]?.[key] ?? STRINGS.en[key] ?? fallback ?? key;
}
